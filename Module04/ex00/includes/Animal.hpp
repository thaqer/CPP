#ifndef ANIMAL_HPP
#define ANIMAL_HPP

#include <iostream>
#include <string>

// Virtual destructor ensures proper cleanup of derived classes
// Virtual function allows derived classes to override makeSound() (polymorphic behavior)

class Animal
{
protected:
	std::string type;

public:
	Animal();
	Animal(const Animal& other);
	Animal& operator=(const Animal& other);
	virtual ~Animal();

	std::string getType() const;
	virtual void makeSound() const;
};

#endif