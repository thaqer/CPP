#include "Animal.hpp"
#include "WrongAnimal.hpp"
#include "WrongCat.hpp"
#include "Dog.hpp"
#include "Cat.hpp"

/*this ex help us to understand the concept of polymorphism
and virtual functions and go deeper in inheritance and deep copying.
*/

int main()
{
	const Animal* meta = new Animal();
	const Animal* j = new Dog();
	const Animal* i = new Cat();
	std::cout << j->getType() << " " << std::endl;
	std::cout << i->getType() << " " << std::endl;
	i->makeSound(); //will output the cat sound!
	j->makeSound(); //will output the dog sound!
	meta->makeSound(); //will output the animal sound!

	const WrongAnimal* wrongMeta = new WrongAnimal();
	const WrongAnimal* wrongCat = new WrongCat();
	std::cout << wrongCat->getType() << " " << std::endl;
	wrongCat->makeSound(); //will output the WrongAnimal sound!
	wrongMeta->makeSound(); //will output the WrongAnimal sound!

	delete meta;
	delete j;
	delete i;

	delete wrongMeta;
	delete wrongCat;
	return 0;
}
